"""Generates real Terraform per provider, for the placements the format can hold.

The HCL is real in the sense that matters for E5: each file declares the
resources a team would actually apply, with the attributes those resources
actually take, and the manifest written beside the files records which
placements got resource blocks and which got none, so the blockless count is
parsed and counted rather than asserted. No terraform binary and no cloud
account is assumed; a reader with the binary can run `terraform init` and
`terraform validate` themselves, and ADR-002 records exactly which claims that
step, a plan, and an apply would each add.

The point of generating it is not to deploy. It is to hold the infrastructure
definition next to the cost model and count, mechanically, how many of the
quantities the bill depends on can appear in it at all. That count is experiment
E5, and it is the unit mismatch made concrete: the definition can be complete and
the cost still is not in it.
"""

from __future__ import annotations

from pathlib import Path

from ..config import TERRAFORM_DIR, Scenario


def _aws(scenario: Scenario) -> str:
    memory_mb = int(scenario.serverless_memory_gb * 1024)
    return f'''# Generated by inference-unit-economics. Real resources, offline: see ADR-002.

terraform {{
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}
}}

provider "aws" {{
  region = "us-east-1"
}}

resource "aws_sagemaker_model" "model" {{
  name               = "iue-model"
  execution_role_arn = var.execution_role_arn

  primary_container {{
    image          = var.inference_image
    model_data_url = var.model_data_url
  }}
}}

# Placement: realtime_dedicated. Sized for peak by a number computed outside
# Terraform, because capacity lives in the throughput profile, not here.
resource "aws_sagemaker_endpoint_configuration" "dedicated" {{
  name = "iue-dedicated"

  production_variants {{
    variant_name           = "primary"
    model_name             = aws_sagemaker_model.model.name
    instance_type          = "ml.m5.large"
    initial_instance_count = var.dedicated_instance_count
  }}
}}

resource "aws_sagemaker_endpoint" "dedicated" {{
  name                 = "iue-dedicated"
  endpoint_config_name = aws_sagemaker_endpoint_configuration.dedicated.name
}}

# Placement: realtime_autoscaled.
resource "aws_appautoscaling_target" "endpoint" {{
  max_capacity       = var.autoscale_max_instances
  min_capacity       = {scenario.autoscale_min_instances}
  resource_id        = "endpoint/${{aws_sagemaker_endpoint.dedicated.name}}/variant/primary"
  scalable_dimension = "sagemaker:variant:DesiredInstanceCount"
  service_namespace  = "sagemaker"
}}

resource "aws_appautoscaling_policy" "endpoint" {{
  name               = "iue-invocations-per-instance"
  policy_type        = "TargetTrackingScaling"
  resource_id        = aws_appautoscaling_target.endpoint.resource_id
  scalable_dimension = aws_appautoscaling_target.endpoint.scalable_dimension
  service_namespace  = aws_appautoscaling_target.endpoint.service_namespace

  target_tracking_scaling_policy_configuration {{
    predefined_metric_specification {{
      predefined_metric_type = "SageMakerVariantInvocationsPerInstance"
    }}
    # The one attribute that encodes capacity, and Terraform cannot compute it:
    # it is instance throughput times the utilization target, which only the
    # profile knows. It arrives as a variable filled in from the measurement.
    target_value = var.invocations_per_instance_target
  }}
}}

# Placement: serverless.
resource "aws_sagemaker_endpoint_configuration" "serverless" {{
  name = "iue-serverless"

  production_variants {{
    variant_name = "primary"
    model_name   = aws_sagemaker_model.model.name

    serverless_config {{
      memory_size_in_mb = {memory_mb}
      max_concurrency   = var.serverless_max_concurrency
    }}
  }}
}}

resource "aws_sagemaker_endpoint" "serverless" {{
  name                 = "iue-serverless"
  endpoint_config_name = aws_sagemaker_endpoint_configuration.serverless.name
}}

# Placement: batch. There is no resource block here, and that absence is the
# finding: a SageMaker Batch Transform job is an API call with a lifetime, not
# infrastructure, so the placement with the lowest unit cost in the comparison
# has no representation in the file a review would read.

variable "execution_role_arn" {{ type = string }}
variable "inference_image" {{ type = string }}
variable "model_data_url" {{ type = string }}
variable "dedicated_instance_count" {{ type = number }}
variable "autoscale_max_instances" {{ type = number }}
variable "invocations_per_instance_target" {{ type = number }}
variable "serverless_max_concurrency" {{ type = number }}
'''


def _gcp(scenario: Scenario) -> str:
    memory = f"{scenario.serverless_memory_gb:g}Gi"
    cpus = f"{scenario.serverless_vcpus:g}"
    return f'''# Generated by inference-unit-economics. Real resources, offline: see ADR-002.

terraform {{
  required_providers {{
    google = {{
      source  = "hashicorp/google"
      version = "~> 6.0"
    }}
  }}
}}

provider "google" {{
  project = var.project
  region  = "us-central1"
}}

# Placements: realtime_dedicated and realtime_autoscaled. The endpoint is a
# Terraform resource; deploying a model onto it with a machine type and a node
# range happens through the deploy API, so even the instance count lives at the
# edge of what this file can say.
resource "google_vertex_ai_endpoint" "endpoint" {{
  name         = "iue-endpoint"
  display_name = "iue-endpoint"
  location     = "us-central1"
}}

# Placement: serverless (Cloud Run, request based billing).
resource "google_cloud_run_v2_service" "serverless" {{
  name     = "iue-serverless"
  location = "us-central1"

  template {{
    containers {{
      image = var.inference_image

      resources {{
        limits = {{
          cpu    = "{cpus}"
          memory = "{memory}"
        }}
      }}
    }}

    scaling {{
      min_instance_count = 0
      max_instance_count = var.serverless_max_instances
    }}
  }}
}}

# Placement: batch. A Vertex AI batch prediction is a job submitted against a
# model, not a resource this file can hold. Same absence, same finding.

variable "project" {{ type = string }}
variable "inference_image" {{ type = string }}
variable "serverless_max_instances" {{ type = number }}
'''


def _azure(scenario: Scenario) -> str:
    return f'''# Generated by inference-unit-economics. Real resources, offline: see ADR-002.

terraform {{
  required_providers {{
    azurerm = {{
      source  = "hashicorp/azurerm"
      version = "~> 4.0"
    }}
  }}
}}

provider "azurerm" {{
  features {{}}
}}

resource "azurerm_resource_group" "rg" {{
  name     = "iue"
  location = "eastus"
}}

# Placements: realtime_dedicated and realtime_autoscaled run on an Azure ML
# managed online endpoint. The endpoint deployment that names the VM size and
# instance count is managed through the ML control plane rather than a stable
# azurerm resource, so the attributes that drive the instance hour bill sit
# outside this file.
resource "azurerm_machine_learning_workspace" "ws" {{
  name                    = "iue-workspace"
  location                = azurerm_resource_group.rg.location
  resource_group_name     = azurerm_resource_group.rg.name
  application_insights_id = var.application_insights_id
  key_vault_id            = var.key_vault_id
  storage_account_id      = var.storage_account_id

  identity {{
    type = "SystemAssigned"
  }}
}}

# Placement: serverless (Azure Container Instances). Billed for the lifetime of
# the group, whether or not a request arrives: the rate card calls this
# serverless and the billing unit disagrees.
resource "azurerm_container_group" "serverless" {{
  name                = "iue-serverless"
  location            = azurerm_resource_group.rg.location
  resource_group_name = azurerm_resource_group.rg.name
  os_type             = "Linux"

  container {{
    name   = "inference"
    image  = var.inference_image
    cpu    = {scenario.serverless_vcpus:g}
    memory = {scenario.serverless_memory_gb:g}

    ports {{
      port     = 8080
      protocol = "TCP"
    }}
  }}
}}

# Placement: batch. The compute cluster could be declared here; the job that
# runs on it, whose setup window is most of this model's batch bill, cannot.

variable "inference_image" {{ type = string }}
variable "application_insights_id" {{ type = string }}
variable "key_vault_id" {{ type = string }}
variable "storage_account_id" {{ type = string }}
'''


GENERATORS = {"aws": _aws, "gcp": _gcp, "azure": _azure}

#: Which resource addresses each placement's definition consists of, plus the
#: scaffolding every placement shares. An empty placement list is a placement
#: with no resource block: a job, not infrastructure. The coverage map
#: verifies every listed address against the parsed files in both directions
#: (nothing phantom, nothing unclaimed) and counts the empty lists, so the
#: "no resource block at all" sentence in the documents is a computed figure.
SHARED_RESOURCES: dict[str, list[str]] = {
    "aws": ["aws_sagemaker_model.model"],
    "gcp": [],
    "azure": ["azurerm_resource_group.rg"],
}

RESOURCES_BY_PLACEMENT: dict[str, dict[str, list[str]]] = {
    "aws": {
        "realtime_dedicated": [
            "aws_sagemaker_endpoint_configuration.dedicated",
            "aws_sagemaker_endpoint.dedicated",
        ],
        "realtime_autoscaled": [
            "aws_appautoscaling_target.endpoint",
            "aws_appautoscaling_policy.endpoint",
        ],
        "serverless": [
            "aws_sagemaker_endpoint_configuration.serverless",
            "aws_sagemaker_endpoint.serverless",
        ],
        "batch": [],
    },
    "gcp": {
        "realtime_dedicated": ["google_vertex_ai_endpoint.endpoint"],
        "realtime_autoscaled": ["google_vertex_ai_endpoint.endpoint"],
        "serverless": ["google_cloud_run_v2_service.serverless"],
        "batch": [],
    },
    "azure": {
        "realtime_dedicated": ["azurerm_machine_learning_workspace.ws"],
        "realtime_autoscaled": ["azurerm_machine_learning_workspace.ws"],
        "serverless": ["azurerm_container_group.serverless"],
        "batch": [],
    },
}


def generate_all(scenario: Scenario | None = None,
                 out_dir: Path = TERRAFORM_DIR) -> dict[str, Path]:
    import json

    scenario = scenario or Scenario()
    out_dir.mkdir(parents=True, exist_ok=True)
    written = {}
    for provider, generator in GENERATORS.items():
        path = out_dir / f"{provider}.tf"
        path.write_text(generator(scenario), encoding="utf-8")
        written[provider] = path
    (out_dir / "manifest.json").write_text(
        json.dumps({"resources_by_placement": RESOURCES_BY_PLACEMENT,
                    "shared_resources": SHARED_RESOURCES}, indent=2)
        + "\n", encoding="utf-8")
    return written


if __name__ == "__main__":
    for path in generate_all().values():
        print(f"wrote {path}")
